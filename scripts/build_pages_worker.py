"""Pack site/ into a single Cloudflare Pages `_worker.js`.

Why this exists: in Claude Code cloud sessions the network proxy injects the
saved Cloudflare API token into every request to api.cloudflare.com, which
overwrites the short-lived upload JWT that `wrangler pages deploy` uses for
asset uploads. A Pages deployment can instead carry a `_worker.js` (advanced
mode), uploaded with the deployment request itself using the API token. This
script embeds every file in site/ into that worker so it serves the whole
site. On your own machine, plain `npx wrangler pages deploy` works and is
simpler.

Usage: python3 scripts/build_pages_worker.py site build/_worker.js
"""

import base64
import json
import mimetypes
import pathlib
import sys

SKIP = {"_headers", "_redirects", ".DS_Store"}
TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".woff2": "font/woff2",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
    ".json": "application/json",
    ".txt": "text/plain; charset=utf-8",
    ".vcf": "text/vcard; charset=utf-8",
}

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
files = {}
for p in sorted(src.rglob("*")):
    if not p.is_file() or p.name in SKIP or p.name.endswith(('.webp.json', '.png.json', '.jpg.json')):
        continue
    rel = "/" + p.relative_to(src).as_posix()
    ctype = TYPES.get(p.suffix.lower()) or mimetypes.guess_type(p.name)[0] or "application/octet-stream"
    files[rel] = [ctype, base64.b64encode(p.read_bytes()).decode("ascii")]

worker = """// Generated by scripts/build_pages_worker.py. Do not edit by hand.
const FILES = %s;
const decoded = new Map();
const bytes = (p) => {
  let u = decoded.get(p);
  if (!u) {
    const s = atob(FILES[p][1]);
    u = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i);
    decoded.set(p, u);
  }
  return u;
};
const SECURITY = {
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'strict-origin-when-cross-origin',
  'permissions-policy': 'camera=(), microphone=(), geolocation=()',
  'x-frame-options': 'DENY',
};
export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { allow: 'GET, HEAD' } });
    }
    const url = new URL(request.url);
    let p;
    try { p = decodeURIComponent(url.pathname); } catch (e) { p = url.pathname; }
    if (p.endsWith('/')) p += 'index.html';
    if (!FILES[p] && FILES[p + '.html']) p += '.html';
    if (!FILES[p] && FILES[p + '/index.html']) {
      return Response.redirect(url.origin + url.pathname + '/' + url.search, 308);
    }
    let status = 200;
    if (!FILES[p]) { p = '/404.html'; status = 404; }
    const headers = new Headers(SECURITY);
    headers.set('content-type', FILES[p][0]);
    if (p.startsWith('/card/')) headers.set('x-robots-tag', 'noindex, nofollow');
    headers.set('cache-control',
      status !== 200 ? 'no-store'
      : p.startsWith('/fonts/') ? 'public, max-age=31536000, immutable'
      : p.startsWith('/assets/') || p.endsWith('.png') || p.endsWith('.svg') ? 'public, max-age=86400'
      : 'public, max-age=300, must-revalidate');
    return new Response(request.method === 'HEAD' ? null : bytes(p), { status, headers });
  },
};
""" % json.dumps(files, separators=(",", ":"))

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(worker)
print(f"{len(files)} files packed into {out} ({out.stat().st_size / 1024:.0f} KB)")
for k in files:
    print("  ", k)
